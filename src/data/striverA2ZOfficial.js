function parseOfficialSnapshot(html) {
  const flightChunks = [];
  const pattern = /self\.__next_f\.push\(\[1,"((?:\\.|[^"\\])*)"\]\)/g;
  let match;
  while ((match = pattern.exec(html))) {
    try {
      flightChunks.push(JSON.parse(`"${match[1]}"`));
    } catch {
      // Ignore unrelated flight chunks that are not valid JSON strings.
    }
  }

  const start = flightChunks.findIndex(chunk => chunk.includes('"sections":'));
  if (start < 0) throw new Error("Official Striver snapshot is missing sections");
  const end = flightChunks.findIndex((chunk, index) => index > start && chunk.startsWith("1c:I"));
  const streamText = flightChunks.slice(start, end < 0 ? flightChunks.length : end).join("");
  const objectStart = streamText.indexOf('{"title":"Striver');
  if (objectStart < 0) throw new Error("Official Striver snapshot payload was not found");
  let objectEnd = -1;
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let index = objectStart; index < streamText.length; index += 1) {
    const character = streamText[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') {
      inString = true;
    } else if (character === "{") {
      depth += 1;
    } else if (character === "}" && --depth === 0) {
      objectEnd = index + 1;
      break;
    }
  }
  if (objectEnd < 0) throw new Error("Official Striver snapshot payload is incomplete");
  const payload = JSON.parse(streamText.slice(objectStart, objectEnd));
  return payload.sections.map(section => ({
    id: section.category_id,
    name: section.category_name,
    subs: section.subcategories.map(subsection => ({
      id: subsection.subcategory_id,
      name: subsection.subcategory_name,
      problems: subsection.problems.map(problem => [
        problem.problem_id,
        problem.problem_name,
        problem.article === "$undefined" ? undefined : problem.article,
        problem.youtube === "$undefined" ? undefined : problem.youtube,
        problem.leetcode === "$undefined" ? undefined : problem.leetcode,
        problem.plus === "$undefined" ? undefined : problem.plus,
        problem.difficulty,
      ]),
    })),
  }));
}

